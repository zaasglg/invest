const displayNames = new Intl.DisplayNames(['kk-KZ', 'kk'], {
    type: 'region',
});

export const INVESTOR_COUNTRIES: InvestorCountry[] = ISO_ALPHA_2_CODES.map(
    (code) => ({
        code,
        label: KAZAKH_LABEL_OVERRIDES[code] ?? displayNames.of(code) ?? code,
        coordinates: COUNTRY_COORDINATES[code],
    }),
).sort((left, right) => left.label.localeCompare(right.label, 'kk'));

const INVESTOR_COUNTRY_BY_CODE = new Map(
    INVESTOR_COUNTRIES.map((country) => [country.code, country]),
);

export function findInvestorCountry(
    code: string | null | undefined,
): InvestorCountry | undefined {
    return code ? INVESTOR_COUNTRY_BY_CODE.get(code.toUpperCase()) : undefined;
}

export function investorCountryLabel(code: string | null | undefined): string {
    return findInvestorCountry(code)?.label ?? code?.toUpperCase() ?? '—';
}
